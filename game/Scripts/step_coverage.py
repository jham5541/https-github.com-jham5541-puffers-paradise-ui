#!/usr/bin/env python3
"""Offline mirror of FPuffersStepRules::Resolve.

Reads Content/Data/Steps/StepRules.json and every Content/Data/Missions/*.json, resolves each
objective to its gameplay exactly the way the game does, and writes Docs/StepCoverage.md.
Exits non-zero if any objective outside an excluded mission falls back to the stand-in prop.

Usage: python3 Scripts/step_coverage.py [--missions DIR ...] [--out Docs/StepCoverage.md]
"""
import argparse, collections, glob, json, os, sys

KNOWN = {"Reach", "EnterVehicle", "Route", "Delivery", "Hold", "Timing", "Mash", "Rhythm", "Memory",
         "Conversation", "Persuade", "Negotiate", "BusinessMenu", "Tail", "Escort", "Chase", "Escape",
         "Stealth", "Approach", "Search", "Photo", "Video", "Defend", "Combat", "Switch", "Scan",
         "LoseHeat", "Prop"}


def is_word_char(c):
    return c.isalnum() or c == "'"


def matches_keyword(text, key):
    if not key:
        return False
    lower, key = text.lower(), key.lower()
    start = 0
    while True:
        at = lower.find(key, start)
        if at < 0:
            return False
        if at == 0 or not is_word_char(lower[at - 1]):
            return True
        start = at + 1


def find_rule(rules, mission_id, obj):
    for index, rule in enumerate(rules.get("KeywordRules", [])):
        types = [t.upper() for t in rule.get("Types", [])]
        if types and obj["Type"].upper() not in types:
            continue
        if rule.get("Missions") and mission_id not in rule["Missions"]:
            continue
        if "Choice" in rule and bool(rule["Choice"]) != bool(obj.get("ChoiceGroup")):
            continue
        keywords = rule.get("Keywords", [])
        if not keywords:
            return index
        if any(matches_keyword(obj.get("Description", ""), k) for k in keywords):
            return index
    return -1


def resolve(rules, mission_id, obj):
    merged = {}
    defaults = {k.upper(): v for k, v in rules.get("Defaults", {}).items()}
    merged.update(defaults.get(obj["Type"].upper(), {}))
    index = find_rule(rules, mission_id, obj)
    if index >= 0:
        merged.update(rules["KeywordRules"][index].get("Params", {}))
    merged.update(rules.get("Overrides", {}).get(obj["Id"], {}))
    merged.setdefault("Gameplay", "Prop")
    if merged["Gameplay"] not in KNOWN:
        merged["Gameplay"] = "Prop"
    return merged, index


def main():
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    parser = argparse.ArgumentParser()
    parser.add_argument("--rules", default=os.path.join(root, "Content/Data/Steps/StepRules.json"))
    parser.add_argument("--missions", nargs="*", default=[os.path.join(root, "Content/Data/Missions")])
    parser.add_argument("--out", default=os.path.join(root, "Docs/StepCoverage.md"))
    args = parser.parse_args()

    rules = json.load(open(args.rules))
    excluded = set(rules.get("ExcludedMissions", []))
    rows, counts, props = [], collections.Counter(), []
    seen = set()
    for folder in args.missions:
        for path in sorted(glob.glob(os.path.join(folder, "*.json"))):
            for mission in json.load(open(path)):
                if mission["Id"] in seen:
                    continue
                seen.add(mission["Id"])
                for obj in mission.get("Objectives", []):
                    if mission["Id"] in excluded:
                        rows.append((mission["Id"], obj, {"Gameplay": "(own level)"}, -1))
                        continue
                    params, index = resolve(rules, mission["Id"], obj)
                    counts[params["Gameplay"]] += 1
                    if params["Gameplay"] == "Prop":
                        props.append(obj["Id"])
                    rows.append((mission["Id"], obj, params, index))

    total = sum(counts.values())
    out = ["# Step gameplay coverage", "",
           "Generated by `Scripts/step_coverage.py` from `Content/Data/Steps/StepRules.json`. "
           "Do not edit by hand.", "",
           f"{len(seen)} missions, {total} objectives with gameplay, {len(props)} on the stand-in prop.", "",
           "| Gameplay | Objectives |", "|---|---|"]
    for name, n in counts.most_common():
        out.append(f"| {name} | {n} |")
    out += ["", "| Mission | Objective | Type | Gameplay | Extras | Description |", "|---|---|---|---|---|---|"]
    for mission_id, obj, params, _ in rows:
        extras = ", ".join(f"{k}={v}" for k, v in params.items() if k not in ("Gameplay",))
        desc = obj.get("Description", "").replace("|", "/")
        out.append(f"| {mission_id} | {obj['Id']} | {obj['Type']} | {params['Gameplay']} | {extras} | {desc} |")
    os.makedirs(os.path.dirname(args.out), exist_ok=True)
    open(args.out, "w").write("\n".join(out) + "\n")
    print(f"{len(seen)} missions, {total} objectives; " + ", ".join(f"{k} {v}" for k, v in counts.most_common()))
    if props:
        print("On the stand-in prop:", ", ".join(props))
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
